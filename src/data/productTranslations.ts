export const getLocalizedProduct = (
  product: ProductItem,
  lang: Language
): ProductItem => {
  const langDict = localizedProductsData[lang] || localizedProductsData['en'] || localizedProductsData['zh'];
  const localized = langDict[product.id];
  if (!localized) return product;

  return {
    ...product,
    name: localized.name || product.name,
    nameEn: localized.nameEn || product.nameEn,
    origin: localized.origin || product.origin,
    specification: localized.specification || product.specification,
    ingredientsHighlight: localized.ingredientsHighlight || product.ingredientsHighlight,
    highlight: localized.highlight || product.highlight,
    badge: localized.badge || product.badge,
    category: localized.category || product.category,
    channels: localized.channels || product.channels,
    targetMarkets: localized.targetMarkets || product.targetMarkets,
  };
};
